"""The `generated` source: a motion card made by FFmpeg (no download, no third-party media).

A card = a soft, slowly moving colour gradient with big text on it: the figure of a
statistic ("40%", exactly as the narration says it - see cards.py) or the key word of an abstract
line ("TRUST"). The text fades in; it never counts up (that would show numbers nobody said).
No faces, no logos, no AI model: generated=true, ai_generated=false.
render.py draws it; here we only describe it as a Candidate.
"""
import hashlib

from app.config import get_settings
from app.pipeline.providers.base import Candidate, Provider

# Calm colour pairs (start, end of the gradient), mid-dark so white text reads well
# but not so dark that the black-frame check fires.
PALETTES = [("0x355C7D", "0x6C5B7B"), ("0x2B5876", "0x4E4376"), ("0x1F6F78", "0x3E8E7E"),
            ("0x4B6CB7", "0x3A4E8C"), ("0x5D4157", "0x838CC7"), ("0x3C6E71", "0x284B63")]
LICENCE_NAME = "Generated by broll-engine (FFmpeg motion card)"


class GeneratedProvider(Provider):
    name = "generated"
    api_info = "FFmpeg gradients + libass text (made locally)"
    cache_across_jobs = False  # made locally, nothing to cache
    media_kind = "generated"

    def card(self, scene_index: int, headline: str, label: str = "") -> Candidate:
        palette = PALETTES[(get_settings().SEED + scene_index) % len(PALETTES)]
        digest = hashlib.sha1(f"{scene_index}|{headline}|{label}".encode()).hexdigest()[:8]
        return Candidate(
            provider=self.name, id=f"card-{scene_index:03d}-{digest}", kind="generated",
            title=f"{headline} {label}".strip(), licence_name=LICENCE_NAME, licence_url="",
            attribution="", page_url="", generated=True, ai_generated=False,
            extra={"headline": headline, "label": label, "palette": list(palette)})

    def search(self, query, orientation, min_duration):
        """Same interface as the other providers: one card showing the query's words."""
        return [self.card(0, query)]

    def fetch(self, candidate, dest_dir):
        return None  # nothing to download: render.py draws the card
